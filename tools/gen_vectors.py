#!/usr/bin/env python3
"""Write test/vectors/frames.txt from the Python reference codec.

The C unit test (firmware/test/test_proto.c) reads the same file and checks
that its encoder produces identical bytes, so the node, gateway and host can
never disagree about the frame layout.

    python3 tools/gen_vectors.py            # rewrite the file
    python3 tools/gen_vectors.py --check    # fail if the file is stale (CI)
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "host"))

from safenode_host.protocol import Flag, Frame, MsgType, State  # noqa: E402

OUT = ROOT / "test" / "vectors" / "frames.txt"

VECTORS = [
    # Example line of Technical Documentation Section V-D
    Frame(3, MsgType.ALERT, 1287, State.DANGER, Flag.FLAME | Flag.LATCHED, 412, 3125, 3980, 0, 0, 86400),
    Frame(1, MsgType.HEARTBEAT, 0, State.NORMAL, 0, 2500, 2850, 4100, 0, 1, 3),
    Frame(20, MsgType.FAULT, 65534, State.FAULT, Flag.GAS_FAULT | Flag.TEMP_FAULT, 0, -1250, 0, 3, 15, 0xFFFFFF),
    Frame(7, MsgType.WARNING, 42, State.WARNING, Flag.LOW_BATT, 560, 3010, 3390, 5, 2, 12345),
    Frame(12, MsgType.ALERT, 9, State.DANGER, Flag.VIA_ESPNOW | Flag.LATCHED, 400, 5200, 3700, 2, 4, 777),
]


def render() -> str:
    lines = [
        "# SAFE-NODE frame test vectors. Generated by tools/gen_vectors.py; do not edit.",
        "# node type seq state flags gas_x1000 temp_x100 vbat_mv reset_cause reset_count uptime_s hex",
    ]
    for f in VECTORS:
        lines.append(
            f"{f.node_id} {int(f.type)} {f.seq} {int(f.state)} {f.flags} {f.gas_x1000} {f.temp_x100} "
            f"{f.vbat_mv} {f.reset_cause} {f.reset_count} {f.uptime_s} {f.encode().hex()}"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify instead of writing")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run tools/gen_vectors.py", file=sys.stderr)
            return 1
        print("vectors up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(VECTORS)} vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
